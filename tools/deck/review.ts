/**
 * Review checks for built decks.
 *
 * Manpage text keeps its license (often GPL or GFDL for GNU tools). Option
 * descriptions are shown with attribution, but `core` summaries are the text
 * every learner sees on every card, so they're written in our own words.
 * `copiedSummaries` finds the ones that still read like the manpage, and
 * `attributionsMarkdown` renders ATTRIBUTIONS.md from deck metadata.
 */
import { findCloze } from '../../src/schema/cards'
import type { Deck, Option } from '../../src/schema/deck'

function words(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
}

/**
 * True when a summary is a close copy of the option's (manpage) description:
 * it is the description's opening words, or at least 80% of its words appear
 * in the description's first sentence. Very short summaries (under four
 * words) are too generic to be a meaningful copy.
 */
export function isCopiedSummary(option: Pick<Option, 'summary' | 'description'>): boolean {
  const summary = words(option.summary)
  if (summary.length < 4 || !option.description) return false
  const description = words(option.description)
  if (summary.every((word, index) => description[index] === word)) return true
  const firstSentence = new Set(words(option.description.split(/(?<=\.)\s/)[0] ?? ''))
  const shared = summary.filter((word) => firstSentence.has(word)).length
  return shared / summary.length >= 0.8
}

/** IDs of visible `core` options whose summary is a close copy of the description. */
export function copiedSummaries(deck: Deck): string[] {
  return deck.options
    .filter((option) => option.tier === 'core' && !option.hidden && isCopiedSummary(option))
    .map((option) => option.id)
}

/**
 * IDs of visible `core` options with no example that can make a cloze card:
 * one that spells a flag as its own token. `tar -czf` doesn't count for `-z`.
 */
export function coreWithoutExamples(deck: Deck): string[] {
  return deck.options
    .filter((option) => option.tier === 'core' && !option.hidden && !findCloze(option))
    .map((option) => option.id)
}

/** ATTRIBUTIONS.md: one section per deck, from its `license` and `attribution`. */
export function attributionsMarkdown(decks: Deck[]): string {
  const lines = [
    '# Attributions',
    '',
    '<!-- Generated by `pnpm deck:build` from deck metadata. Do not edit. -->',
    '',
    'Deck content is derived from the manual pages and examples listed below. Option descriptions quote the source manpage and keep its license; summaries for `core` options are written for this project.',
    '',
  ]
  for (const deck of [...decks].sort((a, b) => a.id.localeCompare(b.id))) {
    const pages = (deck.sourcePages ?? []).map((page) =>
      page.section ? `${page.name}(${page.section})` : page.name,
    )
    lines.push(`## ${deck.tool} (${deck.variant})`, '')
    lines.push(`- Deck: \`${deck.id}\`, generated from ${deck.source} ${deck.toolVersion}`)
    if (pages.length > 0) lines.push(`- Source pages: ${pages.join(', ')}`)
    lines.push(`- License: ${deck.license}`)
    lines.push(`- Attribution: ${deck.attribution}`, '')
  }
  return lines.join('\n')
}
